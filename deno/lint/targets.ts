/// <reference lib="deno.unstable" />
// Reading form targets out of a script's syntax tree (ADR-0026), for the lint plugin's
// brittle-css-target and literal-secret rules. Only literal targets are read: a target built at run
// time cannot be checked ahead of time.
import type { Target } from "../forms/types.ts";

/** Methods whose first argument is a target. */
const TARGET_FIRST = new Set(["fill", "clear", "upload", "click"]);
/** Methods that take `{ within }` as their first argument. */
const WITHIN_OPTION = new Set(["fields", "clickables"]);

type Node = Deno.lint.Node;

function methodName(call: Deno.lint.CallExpression): string | null {
  const callee = call.callee;
  if (callee.type !== "MemberExpression" || callee.computed || callee.property.type !== "Identifier") return null;
  return callee.property.name;
}

/** The argument nodes of a call that are form targets (empty when the call is not a form verb). */
export function targetNodes(call: Deno.lint.CallExpression): Node[] {
  const name = methodName(call);
  const first = call.arguments[0];
  if (!name || !first) return [];
  if (TARGET_FIRST.has(name)) return [first];
  if (WITHIN_OPTION.has(name) && first.type === "ObjectExpression") {
    const within = property(first, "within");
    return within ? [within] : [];
  }
  return [];
}

function property(obj: Deno.lint.ObjectExpression, name: string): Node | null {
  for (const p of obj.properties) {
    if (p.type !== "Property" || p.computed) continue;
    const key = p.key.type === "Identifier" ? p.key.name : p.key.type === "Literal" ? String(p.key.value) : null;
    if (key === name) return p.value as Node;
  }
  return null;
}

function literalString(node: Node): string | null {
  if (node.type === "Literal" && typeof node.value === "string") return node.value;
  if (node.type === "TemplateLiteral" && node.expressions.length === 0) return node.quasis[0]?.cooked ?? null;
  return null;
}

function literalMatcher(node: Node): string | RegExp | null {
  const text = literalString(node);
  if (text !== null) return text;
  const regex = node.type === "Literal" && "regex" in node ? node.regex : undefined;
  return regex ? new RegExp(regex.pattern, regex.flags) : null;
}

/** A target written as a literal in the source, or null when it is computed at run time. */
export function literalTarget(node: Node): Target | null {
  const css = literalString(node);
  if (css !== null) return css;
  if (node.type !== "ObjectExpression") return null;
  for (const p of node.properties) {
    if (p.type !== "Property" || p.computed) return null; // spreads and computed keys: not literal
  }
  const withinNode = property(node, "within");
  const within = withinNode ? literalTarget(withinNode) : undefined;
  if (within === null) return null;
  const extra = within !== undefined ? { within } : {};
  const labelNode = property(node, "label");
  if (labelNode) {
    const label = literalMatcher(labelNode);
    return label === null ? null : { label, ...extra };
  }
  const textNode = property(node, "text");
  if (textNode) {
    const text = literalMatcher(textNode);
    return text === null ? null : { text, ...extra };
  }
  const roleNode = property(node, "role");
  const role = roleNode ? literalString(roleNode) : null;
  if (role === null) return null;
  const nameNode = property(node, "name");
  if (!nameNode) return { role, ...extra };
  const name = literalMatcher(nameNode);
  return name === null ? null : { role, name, ...extra };
}

/** CSS strings inside a literal target: the target itself, or its `within`. */
export function cssNodes(node: Node): Node[] {
  if (literalString(node) !== null) return [node];
  if (node.type !== "ObjectExpression") return [];
  const within = property(node, "within");
  return within ? cssNodes(within) : [];
}

// Mirrors GENERATED in forms/runtime.ts (the runtime is shipped as source and cannot import).
const GENERATED = /[0-9a-f]{8}-[0-9a-f]{4}|\d{4,}|[_-]\d+([_-]|$)|^\W+[a-z]?\d+\W*$/i;

/** Why a CSS selector is likely to break when the site is rebuilt, or null if it looks stable. */
export function brittleness(css: string): string | null {
  if (/:nth-(child|of-type|last-child|last-of-type)\(/.test(css)) return "it picks an element by position";
  for (const m of css.matchAll(/#((?:\\.|[\w-])+)|\[id\s*=\s*["']?([^"'\]]+)/g)) {
    const id = m[1] ?? m[2];
    if (GENERATED.test(id)) return `the id "${id}" looks generated`;
  }
  for (const m of css.matchAll(/\.((?:\\.|[\w-])+)/g)) {
    const cls = m[1];
    const hashed = cls.split(/[-_]+/).some((part) => part.length >= 5 && /\d/.test(part) && /[a-z]/i.test(part));
    if (hashed) return `the class "${cls}" looks generated by a build tool`;
  }
  const steps = css.replace(/\[[^\]]*\]|\([^)]*\)/g, "").trim().split(/\s*[\s>+~]\s*/).filter(Boolean);
  if (steps.length > 3) return `it is a chain of ${steps.length} steps that any layout change breaks`;
  return null;
}
