// Seeds ~/.tranquil/automations/deno.json — the fallback --config for scripts with no project
// deno.json of their own (ADR-0022 specific 8). The import map points "tranquil/automation" at
// the shipped runtime by absolute file: URL, refreshed on package load so app updates take.
// Only files carrying the generated-by marker are ever rewritten; a user who removes the marker
// owns the file.
const fs = require("fs");
const os = require("os");
const path = require("path");
const { pathToFileURL } = require("url");

const MARKER = "generated by tranquil-automations — edits will be overwritten";

function globalDenoConfigPath() {
  return path.join(os.homedir(), ".tranquil", "automations", "deno.json");
}

function modTsPath() {
  return path.join(__dirname, "..", "deno", "mod.ts");
}

function generatedContent() {
  return (
    JSON.stringify(
      {
        "//": MARKER,
        imports: {
          "tranquil/automation": pathToFileURL(modTsPath()).href,
          capnweb: "npm:capnweb@0.9.0",
        },
        tasks: {
          check: "deno check .",
          fmt: "deno fmt",
          lint: "deno lint",
          test: "deno test",
        },
        // deno.ns + dom (instead of the default deno.window): automation scripts pass page
        // callbacks to tab.evaluate(() => document.…), which must type-check.
        compilerOptions: {
          strict: true,
          lib: ["deno.ns", "dom", "dom.iterable", "dom.asynciterable", "esnext"],
        },
      },
      null,
      2
    ) + "\n"
  );
}

function seed() {
  const target = globalDenoConfigPath();
  const content = generatedContent();
  try {
    if (fs.existsSync(target)) {
      const existing = fs.readFileSync(target, "utf8");
      if (existing === content || !existing.includes(MARKER)) return;
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content, "utf8");
  } catch (e) {
    console.warn("[tranquil-automations] deno.json seed failed:", e);
  }
}

module.exports = { seed, globalDenoConfigPath };
