// Seeds ~/.tranquil/automations/deno.json: the one config every automation runs with, wherever
// the script lives (ADR-0022 specific 8). A deno.json near a script belongs to some other
// project and is never used. The import map points "tranquil/automation" at the shipped runtime
// by absolute file: URL, refreshed on package load so app updates take, and gives scripts the
// libraries Tranquil provides (the Deno standard library, capnweb) by short name. Only files carrying the
// generated-by marker are ever rewritten; a user who removes the marker owns the file.
const fs = require("fs");
const os = require("os");
const path = require("path");
const { pathToFileURL } = require("url");

const MARKER = "generated by tranquil-automations — edits will be overwritten";

function globalDenoConfigPath() {
  return path.join(os.homedir(), ".tranquil", "automations", "deno.json");
}

function modTsPath() {
  return path.join(__dirname, "..", "deno", "mod.ts");
}

// The Deno standard library modules scripts can import by short name ("@std/async/delay").
// Pinned, and bumped with Tranquil releases; anything else a script imports in full (jsr:…, npm:…).
const STD = {
  assert: "1.0.19",
  async: "1.5.1",
  collections: "1.4.0",
  csv: "1.0.6",
  encoding: "1.0.11",
  fmt: "1.0.10",
  fs: "1.0.24",
  http: "1.1.4",
  path: "1.1.6",
  testing: "1.0.21",
  text: "1.1.0",
};

function generatedContent() {
  return (
    JSON.stringify(
      {
        "//": MARKER,
        imports: {
          "tranquil/automation": pathToFileURL(modTsPath()).href,
          // Test-only helpers: fieldsOf()/fieldOf() run the form resolver over saved HTML.
          "tranquil/automation/testing": pathToFileURL(path.join(__dirname, "..", "deno", "testing.ts")).href,
          // The same version the SDK's RPC bridge uses, for scripts that speak Cap'n Web themselves.
          capnweb: "npm:capnweb@0.9.0",
          ...Object.fromEntries(Object.entries(STD).map(([name, v]) => [`@std/${name}`, `jsr:@std/${name}@^${v}`])),
        },
        // The Tranquil plugin keeps page code explicit (ADR-0026). no-import-prefix is off:
        // standalone scripts are expected to import jsr:/npm: modules inline.
        lint: {
          plugins: [pathToFileURL(path.join(__dirname, "..", "deno", "lint", "tranquil.ts")).href],
          rules: { exclude: ["no-import-prefix"] },
        },
        tasks: {
          check: "deno check .",
          fmt: "deno fmt",
          lint: "deno lint",
          test: "deno test",
        },
        // Deno's default lib, deliberately without `dom` (ADR-0026): page code gets the typed
        // `page` scope (tab.evaluate((page) => page.document.…)), so a bare `document` in a
        // script is a type error instead of a crash at run time.
        compilerOptions: {
          strict: true,
        },
      },
      null,
      2
    ) + "\n"
  );
}

function seed() {
  const target = globalDenoConfigPath();
  const content = generatedContent();
  try {
    if (fs.existsSync(target)) {
      const existing = fs.readFileSync(target, "utf8");
      if (existing === content || !existing.includes(MARKER)) return;
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content, "utf8");
  } catch (e) {
    console.warn("[tranquil-automations] deno.json seed failed:", e);
  }
}

module.exports = { seed, globalDenoConfigPath };
